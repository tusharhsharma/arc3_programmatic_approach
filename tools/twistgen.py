def room(rows):
    """pad a 14-row interior into a 16x16 map with a wall border"""
    assert len(rows) == 14 and all(len(r) == 14 for r in rows), [len(r) for r in rows]
    return ["#" * 16] + ["#" + r + "#" for r in rows] + ["#" * 16]


