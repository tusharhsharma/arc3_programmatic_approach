def _sq(color, name, cx, cy, layer=0):
    return Sprite(pixels=[[color] * CELL for _ in range(CELL)], name=name,
                  visible=True, collidable=False, layer=layer).set_position(cx * CELL, cy * CELL)


LEGEND = {{"#": ("wall", 0), "T": ("pen", 0), "M": ("mark", 0), "X": ("line", 0), "S": ("pad", 0),
          "B": ("block", 1), "H": ("helper", 2), "P": ("player", 2)}}


def _sprites_for(m, law):
    out = []
    for r, row in enumerate(m):
        for c, ch in enumerate(row):
            if ch in LEGEND:
                name, layer = LEGEND[ch]
                out.append(_sq(C[name], name, c, r, layer))
    if law.get("budget"):
        for i in range(BUDGET_MAX):
            out.append(_sq(C["hud"], "hud", 1 + i, 0, 3))
    return out


levels = [Level(sprites=_sprites_for(m, law), name=f"lv{{i}}") for i, (m, law) in enumerate(zip(MAPS, LAWS))]
VEC = {{1: (0, -1), 2: (0, 1), 3: (-1, 0), 4: (1, 0)}}


