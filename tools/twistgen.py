def emit(name, g):
    d = OUT / name
    d.mkdir(parents=True, exist_ok=True)
    maps = [[r.replace("T", "T") for r in m] for m in g["maps"]]
    # the pen cells of a 2x2 pen are also where the block must rest; the map's T cells are exactly those
    src = TEMPLATE.format(title=g["title"], colours=json.dumps(COLOURS), laws=json.dumps(g["laws"]),
                          maps=json.dumps(maps, indent=1), slide=g["slide"], cls=name.capitalize(), gid=name)
    (d / f"{name}.py").write_text(src)
    meta = {"game_id": f"{name}-sim000000", "title": f"twist: {g['title']}", "tags": ["sim-twist"], "private_tags": [],
            "level_tags": [["sim"]] * 3, "baseline_actions": g["baselines"], "date_downloaded": "2026-10-13T00:00:00Z",
            "twist": {"laws": g["laws"], "note": "L1-2 teach the law; L3 breaks it under the same skin"}}
    (d / "metadata.json").write_text(json.dumps(meta, indent=2))
    return d / f"{name}.py"


def check(name, path, max_nodes=40000):
    """breadth-first search over the engine itself (sprite snapshots restored in place): every level must
    have a solution, and its length is the level's baseline"""
    from collections import deque
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    from arcengine import GameAction, GameState
    from arcengine.enums import ActionInput
    game = getattr(mod, name.capitalize())()
    fd = game.perform_action(ActionInput(id=GameAction.RESET))

    def snap():
        lv = game.current_level
        return (tuple((s.name, s.x, s.y, s.is_visible) for s in lv.get_sprites()), game.budget, game.tick)

    def restore(st):
        lv = game.current_level
        for s, (nm, x, y, vis) in zip(lv.get_sprites(), st[0]):
            s.set_position(x, y); s.set_visible(vis)
        game.budget, game.tick = st[1], st[2]
        game._state = GameState.NOT_FINISHED

    import heapq
    C_ = mod.C

    def h(st):
        """a lower bound on the actions left: the moving things' distance to where they must go"""
        law = mod.LAWS[game.level_index]
        sp = st[0]
        pens = [(x // 4, y // 4) for nm, x, y, _ in sp if nm == "pen"]
        marks = [(x // 4, y // 4) for nm, x, y, _ in sp if nm == "mark"]
        blocks = [(x // 4, y // 4) for nm, x, y, _ in sp if nm == "block"]
        player = [(x // 4, y // 4) for nm, x, y, _ in sp if nm == "player"][0]
        goal = law["goal"]
        if goal == "player_on_pen":
            return min(abs(player[0] - c[0]) + abs(player[1] - c[1]) for c in pens)
        tg = pens if goal == "block_on_pen" else marks
        return sum(min(abs(b[0] - c[0]) + abs(b[1] - c[1]) for c in tg) for b in blocks)

    ok = True
    baselines = []
    for lv in range(3):
        before = fd.levels_completed
        s0 = snap()
        cnt = 0
        q = [(h(s0), 0, cnt, s0, [])]; seen = {s0}; found = None; nodes = 0
        while q and nodes < max_nodes:
            _, g_, _, st, path_ = heapq.heappop(q); nodes += 1
            for k in (1, 2, 3, 4):
                restore(st)
                f2 = game.perform_action(ActionInput(id=GameAction[f"ACTION{k}"]))
                if f2.levels_completed > before:
                    found = (f2, path_ + [k]); break
                if f2.state == GameState.GAME_OVER:
                    continue
                s2 = snap()
                if s2 in seen:
                    continue
                seen.add(s2); cnt += 1
                heapq.heappush(q, (g_ + 1 + h(s2), g_ + 1, cnt, s2, path_ + [k]))
            if found:
                break
        if not found:
            print(f"  {name} L{lv + 1}: NO SOLUTION within {nodes} states"); ok = False; break
        fd, sol = found
        baselines.append(len(sol))
        print(f"  {name} L{lv + 1}: solved in {len(sol)} actions {sol} ({nodes} states searched)")
    return ok, baselines


