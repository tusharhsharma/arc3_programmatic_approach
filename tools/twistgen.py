"""THE TWIST SUITE — the same game, a different law (2026-10-13, Tushar: "you
have to create games with different mechanics ... ally becomes enemy,
supporting becomes damaging ... you get feedback, self-correct and predict
correctly based on some learned skills").

Each game is three levels.  Levels 1 and 2 teach a law; level 3 wears the
same skin and BREAKS it.  What is measured is not the win alone but the
unlearning: the attempt ledger must show the carried law predicting wrong,
the contradiction re-tested, the law re-scoped or dropped, and the level won
under the new one — with no line of the core naming the twist.

  tw01  the helper      L1-2: a second mover pushes blocks toward the pen
                        L3:   it pushes them away           (ally -> enemy)
  tw02  the pads        L1-2: a floor colour refills the budget bar
                        L3:   the same colour drains it     (support -> damage)
  tw03  the line        L1-2: a line the player cannot cross, blocks slide through
                        L3:   the player crosses it; the block waits beyond
  tw04  the goal        L1-2: block onto the pen ends the level
                        L3:   the block starts ON the pen; onto the mark ends it

    .venv/bin/python tools/twistgen.py            -> environment_files/tw01..tw04 (+ a self-check)
    .venv/bin/python tools/core_play2.py tw01:1-3 --no-floor --seconds 300 -v

The governing law of each level is written to metadata.json ("twist") for
the audit only; the core never reads environment_files.
"""
