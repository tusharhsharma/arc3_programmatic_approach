def emit(name, g):
    d = OUT / name
    d.mkdir(parents=True, exist_ok=True)
    src = TEMPLATE.format(colours=json.dumps(COLOURS), laws=json.dumps(g["laws"]), maps=json.dumps(g["maps"], indent=1))
    (d / f"{name}.py").write_text(src)
    meta = {"game_id": f"{name}-sim000000", "title": f"twist: {g['title']}", "tags": ["sim-twist"], "private_tags": [],
            "level_tags": [["sim"]] * 3, "baseline_actions": [0, 0, 0], "date_downloaded": "2026-10-24T00:00:00Z",
            "twist": {"laws": g["laws"], "note": "L1 gravity, L2 the jump, L3 the running jump (momentum); lava in the pits"}}
    (d / "metadata.json").write_text(json.dumps(meta, indent=2))
    return d / f"{name}.py"


def check(name, path, max_nodes=40000):
    """A* over the engine itself: every level must have a solution; its length is the baseline."""
    import heapq
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    from arcengine import GameAction, GameState
    from arcengine.enums import ActionInput
    game = getattr(mod, name.capitalize())()
    fd = game.perform_action(ActionInput(id=GameAction.RESET))

    def snap():
        lv = game.current_level
        return (tuple((s.name, s.x, s.y) for s in lv.get_sprites()), game.facing, game.last_dx)

    def restore(st):
        lv = game.current_level
        for s, (nm, x, y) in zip(lv.get_sprites(), st[0]):
            s.set_position(x, y)
        game.facing, game.last_dx = st[1], st[2]
        game.frames = []
        game._state = GameState.NOT_FINISHED

    def h(st):
        sp = st[0]
        pens = [(x // 4, y // 4) for nm, x, y in sp if nm == "pen"]
        player = [(x // 4, y // 4) for nm, x, y in sp if nm == "player"][0]
        return min(abs(player[0] - c[0]) + abs(player[1] - c[1]) for c in pens) // 3

    ok = True; baselines = []
    for lv in range(3):
        before = fd.levels_completed
        s0 = snap(); cnt = 0
        q = [(h(s0), 0, cnt, s0, [])]; seen = {s0}; found = None; nodes = 0
        while q and nodes < max_nodes:
            _, g_, _, st, path_ = heapq.heappop(q); nodes += 1
            for k in (1, 2, 3, 4):
                restore(st)
                f2 = game.perform_action(ActionInput(id=GameAction[f"ACTION{k}"]))
                if f2.levels_completed > before:
                    found = (f2, path_ + [k]); break
                s2 = snap()
                if s2 in seen:
                    continue
                seen.add(s2); cnt += 1
                heapq.heappush(q, (g_ + 1 + h(s2), g_ + 1, cnt, s2, path_ + [k]))
            if found:
                break
        if not found:
            print(f"  {name} L{lv + 1}: NO SOLUTION within {nodes} states"); ok = False; break
        fd, sol = found
        baselines.append(len(sol))
        print(f"  {name} L{lv + 1}: solved in {len(sol)} actions {sol} ({nodes} states searched)")
    return ok, baselines


if __name__ == "__main__":
    p = emit("tw05", GAME)
    ok, bases = check("tw05", p)
    if ok:
        meta = json.loads((p.parent / "metadata.json").read_text()); meta["baseline_actions"] = bases
        (p.parent / "metadata.json").write_text(json.dumps(meta, indent=2))
    print("all levels solvable" if ok else "A LEVEL HAS NO SOLUTION — fix the map")
    sys.exit(0 if ok else 1)
