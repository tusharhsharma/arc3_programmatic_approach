"""THE FIFTH TWIST — a platformer (2026-10-24, Tushar: "when I press up the
game can send me 5 pixels instead of one … a Super Mario Bros-like 2D game
… the program needs to make sense of the feedback").

tw05 "the jump": a side-view room with ground, ledges and a pen to stand on.
Left/right walk one cell; a press's frames show the whole motion — the walk,
then the FALL one cell a frame until something holds the player.  Up is a
JUMP: an arc of frames (up and forward in the facing direction), then the
fall.  Down does nothing.
  L1  walk off a ledge to the pen below            (gravity: a fall ends on support)
  L2  a gap only a jump crosses                    (the arc read off the frames)
  L3  the same skin; the gap needs the RUNNING jump (momentum: the outcome of a
      — a step in the facing direction just before   press depends on the press before)
      the jump lengthens the arc.  The physics is the game's, not the
      level's: the running jump holds on every level (L2 may show it); the
      pits have LAVA at the bottom — a death, the level begins again
Every level is proved solvable by a search over the engine itself; the
solution length is the baseline.  The governing law is in metadata.json for
the audit only.

    .venv/bin/python tools/platgen.py
    .venv/bin/python tools/core_play2.py tw05:1-3 --no-floor --seconds 300 -v
"""
import json, sys, importlib.util
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "environment_files"

TEMPLATE = r'''"""twist suite: the jump (generated by tools/platgen.py)"""
from arcengine import ARCBaseGame, Camera, Level, Sprite

CELL = 4
N = 16
BG = 0
C = {colours}
LAWS = {laws}
MAPS = {maps}


def _sq(color, name, cx, cy, layer=0):
    return Sprite(pixels=[[color] * CELL for _ in range(CELL)], name=name,
                  visible=True, collidable=False, layer=layer).set_position(cx * CELL, cy * CELL)


LEGEND = {{"#": ("wall", 0), "T": ("pen", 0), "X": ("lava", 0), "P": ("player", 2)}}


def _sprites_for(m):
    out = []
    for r, row in enumerate(m):
        for c, ch in enumerate(row):
            if ch in LEGEND:
                name, layer = LEGEND[ch]
                out.append(_sq(C[name], name, c, r, layer))
    return out


levels = [Level(sprites=_sprites_for(m), name=f"lv{{i}}") for i, m in enumerate(MAPS)]


class Tw05(ARCBaseGame):
    def __init__(self) -> None:
        super().__init__(game_id="tw05", levels=levels, camera=Camera(background=BG, letter_box=BG),
                         available_actions=[1, 2, 3, 4])
        self.facing = 1
        self.last_dx = 0
        self.frames = []        # the motion still to show, one cell position a frame

    def on_set_level(self, level) -> None:
        self.facing = 1
        self.last_dx = 0
        self.frames = []

    def _cell(self, s):
        return (s.x // CELL, s.y // CELL)

    def step(self) -> None:
        lv = self.current_level
        law = LAWS[self.level_index]
        walls = {{self._cell(w) for w in lv.get_sprites_by_name("wall")}}
        pens = {{self._cell(w) for w in lv.get_sprites_by_name("pen")}}
        lava = {{self._cell(w) for w in lv.get_sprites_by_name("lava")}}
        p = lv.get_sprites_by_name("player")[0]

        def free(c):
            return 0 <= c[0] < N and 0 <= c[1] < N and c not in walls

        def supported(c):
            below = (c[0], c[1] + 1)
            return not free(below)

        if self.frames:
            # (a motion in progress: one frame of it)
            nx, ny = self.frames.pop(0)
            p.set_position(nx * CELL, ny * CELL)
            if not self.frames:
                self._finish(p, pens, lava)
            return
        aid = self.action.id
        key = getattr(aid, "value", None)
        if key is None:
            key = int(aid)
        x, y = self._cell(p)
        path = []
        if key in (3, 4):
            dx = -1 if key == 3 else 1
            self.facing = dx
            if free((x + dx, y)):
                x += dx; path.append((x, y))
            self.last_dx = dx if path else 0
        elif key == 1 and supported((x, y)):
            dx = self.facing
            arc = law["arc"]
            if law.get("run") and self.last_dx == dx:
                arc = law["run"]
            x0, y0 = x, y
            for ddx, ddy in arc:
                nx, ny = x0 + ddx * dx, y0 + ddy
                if not free((nx, ny)):
                    if free((x, ny)):           # (the wall ahead: the rise goes on, the forward step is refused)
                        nx = x
                    else:
                        break
                x, y = nx, ny
                path.append((x, y))
            self.last_dx = 0
        else:
            self.last_dx = 0
        # THE FALL: one cell a frame until something holds the player
        while free((x, y + 1)):
            y += 1
            path.append((x, y))
        if not path:
            self._finish(p, pens, lava)
            return
        self.frames = path
        nx, ny = self.frames.pop(0)
        p.set_position(nx * CELL, ny * CELL)
        if not self.frames:
            self._finish(p, pens, lava)

    def _finish(self, p, pens, lava):
        if self._cell(p) in lava:
            self.lose(); self.complete_action(); return
        if self._cell(p) in pens:
            self.next_level()
        self.complete_action()
'''

COLOURS = {"wall": 9, "pen": 8, "lava": 7, "player": 12}

# arcs as (dx, dy) per frame from the take-off cell: the standing jump rises
# one, goes forward two, comes down one — three cells of reach; the running
# jump rises two and goes forward four — five cells
STAND = [(1, -1), (2, -1), (3, 0)]
RUN = [(1, -1), (2, -2), (3, -2), (4, -1), (5, 0)]


